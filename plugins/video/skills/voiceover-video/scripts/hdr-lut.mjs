#!/usr/bin/env node
// HLG (BT.2100 / BT.2020, 10-bit) -> SDR (BT.709) as a 3D LUT.
//
//   node hdr-lut.mjs [--out hlg2709.cube] [--size 33] [--knee 0.75]
//                    [--sat 1.0] [--gamma 1.2] [--exposure 1.0]
//
// WHY THIS EXISTS. An iPhone shoots Dolby Vision 8.4: HEVC 10-bit, BT.2020
// primaries, arib-std-b67 (HLG) transfer. Every stage downstream of this skill
// -- the overlay renderer, the subtitles, libx264 yuv420p -- is sRGB/BT.709.
// Handing the HLG signal straight to `format=yuv420p` does not convert it, it
// only re-tags it: the transfer curve is left alone and the picture comes out
// milky, with lifted blacks and no contrast. It is not obviously broken, which
// is what makes it dangerous -- it just looks like a cheaper camera.
//
// The usual fix is `zscale=t=linear,tonemap,zscale=p=bt709`, and zscale needs
// libzimg, which Homebrew's ffmpeg is not built with. `libplacebo` is not there
// either. So the conversion is baked into a .cube and applied with `lut3d`,
// which exists in every ffmpeg build: no new dependency, and the maths is here
// in the open instead of behind a filter flag.
//
// The chain, per LUT entry:
//   1. inverse HLG OETF        signal   -> scene linear
//   2. HLG OOTF (gamma 1.2)    scene    -> display linear, 1.0 = Lw (1000 nits)
//   3. normalise on diffuse white (HLG 75% = 203 nits) so 1.0 = SDR white
//   4. BT.2020 -> BT.709 gamut, in linear light, negatives clamped
//   5. tone curve: identity below the knee, tanh roll-off above it
//   6. BT.709 OETF
//
// Step 5 is the judgment call. Hable and Reinhard both land diffuse white
// around 0.39-0.52 -- correct for grading a 1000-nit master down, far too dark
// for a face lit by an office window. The knee keeps everything below 0.75
// EXACTLY where the camera put it and only compresses what is above it (the
// window, the lamp), which is the part SDR genuinely cannot hold.

import { writeFileSync } from "node:fs";

const arg = (k, d) => {
  const i = process.argv.indexOf(`--${k}`);
  return i > -1 ? process.argv[i + 1] : d;
};

const OUT = arg("out", "hlg2709.cube");
const N = parseInt(arg("size", "33"), 10);
const KNEE = parseFloat(arg("knee", "0.75"));
const SAT = parseFloat(arg("sat", "1.0"));
const GAMMA = parseFloat(arg("gamma", "1.2")); // HLG system gamma at Lw = 1000
const EXPO = parseFloat(arg("exposure", "1.0"));

// --- 1. inverse HLG OETF (ITU-R BT.2100 table 5) ----------------------------
const A = 0.17883277, B = 1 - 4 * A, C = 0.5 - A * Math.log(4 * A);
const hlgInv = (v) =>
  v <= 0.5 ? (v * v) / 3 : (Math.exp((v - C) / A) + B) / 12;

// --- luma coefficients, BT.2020 ---------------------------------------------
const KR = 0.2627, KG = 0.6780, KB = 0.0593;

// --- 3. display-linear value of HLG diffuse white (signal 0.75) -------------
const eW = hlgInv(0.75);
const WHITE = Math.pow(eW, GAMMA); // 0.2032 at gamma 1.2  ->  203 nits of 1000

// --- 4. BT.2020 -> BT.709, linear light -------------------------------------
const M = [
  [1.6604910, -0.5876411, -0.0728499],
  [-0.1245505, 1.1328999, -0.0083494],
  [-0.0181508, -0.1005789, 1.1187297],
];

// --- 5. the tone curve: identity, then a C1-continuous roll-off -------------
// y(k) = k and y'(k) = 1, so nothing visible happens at the knee itself.
const tone = (x) =>
  x <= KNEE ? x : KNEE + (1 - KNEE) * Math.tanh((x - KNEE) / (1 - KNEE));

// --- 6. BT.709 OETF ----------------------------------------------------------
const oetf = (x) =>
  x < 0.018 ? 4.5 * x : 1.099 * Math.pow(x, 0.45) - 0.099;

const clamp01 = (x) => (x < 0 ? 0 : x > 1 ? 1 : x);

const lines = [
  `# HLG BT.2020 -> SDR BT.709`,
  `# generated by short-editor/scripts/hdr-lut.mjs`,
  `# size=${N} knee=${KNEE} sat=${SAT} gamma=${GAMMA} exposure=${EXPO}`,
  `LUT_3D_SIZE ${N}`,
  `DOMAIN_MIN 0.0 0.0 0.0`,
  `DOMAIN_MAX 1.0 1.0 1.0`,
];

// .cube iterates red fastest, then green, then blue.
for (let ib = 0; ib < N; ib++) {
  for (let ig = 0; ig < N; ig++) {
    for (let ir = 0; ir < N; ir++) {
      const sig = [ir, ig, ib].map((i) => i / (N - 1));

      // 1. scene linear
      const e = sig.map(hlgInv);
      // 2. OOTF -> display linear (1.0 = Lw)
      const ys = KR * e[0] + KG * e[1] + KB * e[2];
      const k = Math.pow(ys, GAMMA - 1);
      // 3. renormalise so 1.0 is SDR diffuse white, not the 1000-nit peak
      let lin = e.map((v) => (k * v * EXPO) / WHITE);

      // 4. gamut
      lin = M.map((row) => Math.max(0, row[0] * lin[0] + row[1] * lin[1] + row[2] * lin[2]));

      // optional saturation, around the BT.709 luma, before the roll-off
      if (SAT !== 1.0) {
        const y = 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
        lin = lin.map((v) => Math.max(0, y + (v - y) * SAT));
      }

      // 5 + 6
      const out = lin.map((v) => clamp01(oetf(tone(v))));
      lines.push(out.map((v) => v.toFixed(6)).join(" "));
    }
  }
}

writeFileSync(OUT, lines.join("\n") + "\n");

// A couple of anchors, so a bad build is obvious without opening the file.
const probe = (v) => {
  const e = hlgInv(v);
  const lin = (Math.pow(e, GAMMA) * EXPO) / WHITE;
  return oetf(tone(Math.max(0, lin)));
};
console.log(`${OUT} — ${N}^3 entries`);
console.log(`  diffuse white (HLG 75%) -> ${(probe(0.75) * 255).toFixed(0)}/255`);
console.log(`  mid grey      (HLG 50%) -> ${(probe(0.5) * 255).toFixed(0)}/255`);
console.log(`  peak          (HLG 100%) -> ${(probe(1.0) * 255).toFixed(0)}/255`);
console.log(`  usage: -vf "format=rgb48le,lut3d=file=${OUT}:interp=tetrahedral,format=yuv420p"`);
console.log(`          + -colorspace bt709 -color_primaries bt709 -color_trc bt709`);
